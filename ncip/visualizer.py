def save_script_only(pdb_file: str, 
                     results: Dict,
                     ligand_name: str = None,
                     output_script: str = "interactions.pml",
                     ligand_info: dict = None) -> bool:
    """
    Save PyMOL script without executing.
    
    Args:
        pdb_file: Path to PDB file
        results: Dictionary of interactions
        ligand_name: Optional ligand name
        output_script: Output script file path
        ligand_info: Optional ligand info dictionary
        
    Returns:
        True if script was saved successfully
    """
    script = generate_pymol_script(
        pdb_file, results, ligand_name,
        output_script.replace('.pml', '.pse'),
        ligand_info
    )
    
    with open(output_script, 'w') as f:
        f.write(script)
    
    print(f"\n✓ PyMOL script saved: {output_script}")
    print(f"  Run with: pymol {output_script}")
    
    return True
